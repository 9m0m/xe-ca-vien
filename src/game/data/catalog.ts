export const INITIAL_FOOD_CATALOG = FULL_FOOD_CATALOG

export const FOOD_CATALOG_MAP: Record<string, FoodItemConfig> = Object.fromEntries(
  FULL_FOOD_CATALOG.map((item) => [item.id, item]),
)

export function getFoodConfig(foodId: string): FoodItemConfig | undefined {
  return FOOD_CATALOG_MAP[foodId]
}

export function getFoodsByTier(tier: number): FoodItemConfig[] {
  return FULL_FOOD_CATALOG.filter((f) => f.unlockTier === tier)
}

export function getFoodsByCategory(category: string): FoodItemConfig[] {
  return FULL_FOOD_CATALOG.filter((f) => f.category === category)
}

export function getUnlockCost(food: FoodItemConfig): number {
  return food.basePrice * 4
}
